import os
import re
import datetime
from fpdf import FPDF

EMOJI_PATTERN = re.compile(
    "["
    "\U00010000-\U0010FFFF"
    "\u2600-\u27BF"
    "\uE000-\uF8FF"
    "\uFE00-\uFE0F"
    "\u200D"
    "]+", flags=re.UNICODE
)

def clean_pdf_text(text: str) -> str:
    """Removes unsupported emoji glyphs and normalizes whitespace."""
    if not text:
        return ""
    # Strip emojis
    cleaned = EMOJI_PATTERN.sub('', text)
    # Normalize tabs
    return cleaned.replace('\t', '    ')

class VedaGuruPDF(FPDF):
    def __init__(self, title="VedaGuru AI Report", subtitle="", language="English"):
        super().__init__()
        self.doc_title = clean_pdf_text(title)
        self.doc_subtitle = clean_pdf_text(subtitle)
        self.language = language
        self.set_auto_page_break(auto=True, margin=15)

        # Assets path
        assets_dir = os.path.join(os.path.dirname(__file__), "assets")
        noto_latin = os.path.join(assets_dir, "NotoSans-Regular.ttf")
        noto_deva = os.path.join(assets_dir, "NotoSansDevanagari-Regular.ttf")

        if os.path.exists(noto_latin) and os.path.exists(noto_deva):
            self.add_font("NotoSans", fname=noto_latin)
            self.add_font("NotoDeva", fname=noto_deva)
            self.set_fallback_fonts(["NotoDeva"])
            self.font_family_name = "NotoSans"
        elif os.path.exists(noto_deva):
            self.add_font("NotoDeva", fname=noto_deva)
            self.font_family_name = "NotoDeva"
        else:
            self.font_family_name = "Helvetica"

    def header(self):
        # 1. Main Title - Saffron Brand Color
        self.set_font(self.font_family_name, size=20)
        self.set_text_color(230, 81, 0) # Deep Saffron
        self.cell(0, 9, "VedaGuru AI", align="C", new_x="LMARGIN", new_y="NEXT")

        # 2. Document Title - Deep Maroon
        self.set_font(self.font_family_name, size=13)
        self.set_text_color(139, 0, 0) # Deep Maroon
        self.cell(0, 7, self.doc_title, align="C", new_x="LMARGIN", new_y="NEXT")

        # 3. Gold Separator Line
        self.ln(2)
        self.set_draw_color(255, 179, 0) # Sacred Gold
        self.set_line_width(0.8)
        self.line(14, self.get_y(), 196, self.get_y())
        self.ln(5)

    def footer(self):
        self.set_y(-14)
        self.set_font(self.font_family_name, size=8)
        self.set_text_color(130, 130, 130)
        date_str = datetime.datetime.now().strftime("%d %b %Y, %I:%M %p")
        self.cell(0, 6, f"Generated by VedaGuru AI • Sanatana Knowledge Engine • {date_str} • Page {self.page_no()}", align="C")

    def print_document(self, content: str):
        self.add_page()

        # Metadata Subtitle Card (if provided)
        if self.doc_subtitle:
            self.set_fill_color(254, 247, 237) # Soft warm cream
            self.set_draw_color(245, 158, 11) # Gold amber border
            self.set_line_width(0.4)
            self.set_font(self.font_family_name, size=10)
            self.set_text_color(120, 53, 15)
            self.multi_cell(0, 6, self.doc_subtitle, border=1, fill=True, align="C", new_x="LMARGIN", new_y="NEXT")
            self.ln(4)

        lines = content.split('\n')
        i = 0
        while i < len(lines):
            raw_line = lines[i].rstrip()
            clean_line = clean_pdf_text(raw_line)

            # Skip empty lines
            if not clean_line.strip():
                self.ln(3)
                i += 1
                continue

            # 1. Detect Markdown Table
            if clean_line.strip().startswith('|') and clean_line.strip().endswith('|'):
                table_lines = []
                while i < len(lines) and clean_pdf_text(lines[i]).strip().startswith('|') and clean_pdf_text(lines[i]).strip().endswith('|'):
                    table_lines.append(clean_pdf_text(lines[i]).strip())
                    i += 1
                self._render_table(table_lines)
                continue

            # 2. Markdown Headings (#, ##, ###)
            if clean_line.startswith('#'):
                heading_level = len(clean_line) - len(clean_line.lstrip('#'))
                heading_text = clean_line.lstrip('#').strip().replace('**', '')
                self.ln(4)
                if heading_level == 1:
                    self.set_font(self.font_family_name, size=14)
                    self.set_text_color(180, 50, 0)
                elif heading_level == 2:
                    self.set_font(self.font_family_name, size=12)
                    self.set_text_color(139, 0, 0)
                else:
                    self.set_font(self.font_family_name, size=11)
                    self.set_text_color(70, 70, 70)

                self.multi_cell(0, 7, heading_text, new_x="LMARGIN", new_y="NEXT")
                self.ln(2)
                i += 1
                continue

            # 3. Bullet list item (- , * , • )
            stripped = clean_line.strip()
            if stripped.startswith(('- ', '* ', '• ')) or re.match(r'^\d+\.\s', stripped):
                self.set_font(self.font_family_name, size=10.5)
                self.set_text_color(35, 35, 35)

                if stripped.startswith(('- ', '* ', '• ')):
                    bullet_text = "   •  " + stripped[2:].replace('**', '')
                else:
                    bullet_text = "   " + stripped.replace('**', '')

                self.multi_cell(0, 6, bullet_text, new_x="LMARGIN", new_y="NEXT")
                i += 1
                continue

            # 4. Standard Paragraph
            self.set_font(self.font_family_name, size=10.5)
            self.set_text_color(40, 40, 40)
            text_without_md = clean_line.replace('**', '')
            self.multi_cell(0, 6, text_without_md, new_x="LMARGIN", new_y="NEXT")
            i += 1

    def _render_table(self, table_lines):
        parsed = []
        for line in table_lines:
            if '---' in line:
                continue
            cells = [c.strip().replace('**', '') for c in line.split('|')[1:-1]]
            if cells:
                parsed.append(cells)

        if not parsed:
            return

        col_count = len(parsed[0])
        usable_width = 182 # 210 - 28 margins
        col_width = usable_width / col_count

        self.ln(2)
        # Header Row
        self.set_fill_color(230, 81, 0)
        self.set_text_color(255, 255, 255)
        self.set_font(self.font_family_name, size=9.5)
        for cell in parsed[0]:
            self.cell(col_width, 7, cell, border=1, fill=True, align="C")
        self.ln()

        # Data Rows
        self.set_text_color(40, 40, 40)
        self.set_font(self.font_family_name, size=9)
        alt = False
        for row in parsed[1:]:
            if alt:
                self.set_fill_color(248, 248, 248)
            else:
                self.set_fill_color(255, 255, 255)

            for col_idx in range(col_count):
                val = row[col_idx] if col_idx < len(row) else ""
                self.cell(col_width, 6, val, border=1, fill=True, align="L")
            self.ln()
            alt = not alt

        self.ln(3)

def create_pdf(title: str, content: str, language: str = "English", subtitle: str = "") -> bytes:
    pdf = VedaGuruPDF(title=title, subtitle=subtitle, language=language)
    pdf.print_document(content)
    return bytes(pdf.output())
