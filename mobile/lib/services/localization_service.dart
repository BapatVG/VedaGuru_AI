  static String tr(String key, [String? lang]) {
    final language = lang ?? currentLanguage;
    final dict = _translations[language] ?? _translations['English']!;
    return dict[key] ?? _translations['English']![key] ?? key;
  }

  /// Global reusable Language Selector bottom sheet for instant one-tap switching anywhere
  static void showLanguageBottomSheet(BuildContext context) {
    final auth = Provider.of<AuthProvider>(context, listen: false);
    showModalBottomSheet(
      context: context,
      backgroundColor: Colors.white,
      shape: const RoundedRectangleBorder(borderRadius: BorderRadius.vertical(top: Radius.circular(24))),
      builder: (_) {
        return Container(
          padding: const EdgeInsets.symmetric(vertical: 20, horizontal: 16),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Padding(
                padding: const EdgeInsets.symmetric(horizontal: 8),
                child: Row(
                  children: [
                    const Icon(Icons.language, color: AppTheme.primarySaffron, size: 22),
                    const SizedBox(width: 10),
                    Text(
                      'Select Language / भाषा चुनें',
                      style: GoogleFonts.cinzel(fontSize: 18, fontWeight: FontWeight.bold, color: AppTheme.textDark),
                    ),
                  ],
                ),
              ),
              const SizedBox(height: 12),
              Flexible(
                child: ListView(
                  shrinkWrap: true,
                  children: supportedLanguages.map((lang) {
                    final isSelected = auth.currentLanguage == lang;
                    return ListTile(
                      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                      tileColor: isSelected ? AppTheme.surfaceElevated : null,
                      leading: Text(
                        isSelected ? '🪔' : '🌐',
                        style: const TextStyle(fontSize: 18),
                      ),
                      title: Text(
                        languageNamesNative[lang] ?? lang,
                        style: GoogleFonts.poppins(
                          fontWeight: isSelected ? FontWeight.bold : FontWeight.normal,
                          color: isSelected ? AppTheme.primarySaffron : AppTheme.textDark,
                          fontSize: 14,
                        ),
                      ),
                      trailing: isSelected ? const Icon(Icons.check_circle, color: AppTheme.primarySaffron) : null,
                      onTap: () {
                        auth.setPreferredLanguage(lang);
                        Navigator.pop(context);
                      },
                    );
                  }).toList(),
                ),
              ),
            ],
          ),
        );
      },
    );
  }
