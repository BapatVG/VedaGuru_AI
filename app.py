def generate_ai_content(prompt=None, contents=None):
    if not client:
        raise Exception("Gemini client is not initialized. Please configure GEMINI_API_KEY.")
    models_to_try = [
        'gemini-3.1-flash-lite',
        'gemini-3.5-flash',
        'gemini-3.5-flash-lite',
        'gemini-3-flash-preview',
        'gemini-2.5-flash',
        'gemini-flash-latest',
        'gemini-pro-latest'
    ]
    content_to_send = contents if contents is not None else prompt
    last_error = None
    for model_name in models_to_try:
        try:
            return client.models.generate_content(
                model=model_name,
                contents=content_to_send,
            )
        except Exception as inner_e:
            last_error = inner_e
            err_str = str(inner_e).lower()
            if any(code in err_str for code in ["503", "429", "504", "404", "not found", "resource_exhausted", "unavailable"]):
                continue
            else:
                raise inner_e
    if last_error:
        raise last_error

