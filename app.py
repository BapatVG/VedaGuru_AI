# Helper function for text-to-speech
def text_to_audio(text, lang='hi'):
    tts = gTTS(text=text, lang=lang)
    fp = io.BytesIO()
    tts.write_to_fp(fp)
    return fp.getvalue()

from fpdf import FPDF
class VedaGuruPDF(FPDF):
    def __init__(self, title="VedaGuru AI Premium Report", language="English"):
        super().__init__()
        self.doc_title = title
        self.language = language
        self.set_auto_page_break(auto=True, margin=15)
        
        # Load custom Unicode fonts for English and Devanagari support
        main_font_path = os.path.join(os.path.dirname(__file__), "assets", "NotoSans-Regular.ttf")
        dev_font_path = os.path.join(os.path.dirname(__file__), "assets", "NotoSansDevanagari-Regular.ttf")
        
        self.has_unicode_font = False
        if os.path.exists(main_font_path) and os.path.exists(dev_font_path):
            self.add_font("NotoSans", "", main_font_path)
            self.add_font("NotoDevanagari", "", dev_font_path)
            self.set_fallback_fonts(["NotoDevanagari"])
            self.has_unicode_font = True

    def header(self):
        self.set_text_color(255, 153, 51)
        if self.has_unicode_font:
            self.set_font("NotoSans", size=24)
        else:
            self.set_font("helvetica", 'B', size=24)
        self.cell(0, 10, "VedaGuru AI", ln=True, align="C")
        
        self.set_text_color(139, 0, 0)
        if self.has_unicode_font:
            self.set_font("NotoSans", size=14)
        else:
            self.set_font("helvetica", 'I', size=14)
        self.cell(0, 10, self.doc_title, ln=True, align="C")
        
        self.ln(5)
        self.set_draw_color(255, 153, 51)
        self.line(10, 35, 200, 35)
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_text_color(128, 128, 128)
        if self.has_unicode_font:
            self.set_font("NotoSans", size=8)
        else:
            self.set_font("helvetica", 'I', size=8)
        date_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        self.cell(0, 10, f"Generated by VedaGuru AI on {date_str} | Page {self.page_no()}", align="C")

    def print_content(self, text):
        self.add_page()
        self.set_text_color(0, 0, 0)
        if self.has_unicode_font:
            self.set_font("NotoSans", size=12)
        else:
            self.set_font("helvetica", size=12)
        clean_text = text.replace("**", "").replace("*", "").replace("#", "")
        self.multi_cell(0, 8, txt=clean_text)

def create_pdf(title, text_content):
    pdf = VedaGuruPDF(title=title)
    pdf.print_content(text_content)
    # Return as bytes
    return pdf.output(dest="S").encode("latin-1", errors="replace") if not pdf.has_unicode_font else bytes(pdf.output(dest="S"))

